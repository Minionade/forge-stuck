package net.neoforged.forgestuck.transformer.jar;

import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import org.junit.jupiter.api.Test;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.Handle;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.commons.ClassRemapper;
import org.objectweb.asm.commons.Remapper;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldInsnNode;
import org.objectweb.asm.tree.InvokeDynamicInsnNode;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;

/**
 * Dev tool (skipped unless {@code FORGESTUCK_SCAN_DIR} and {@code FORGESTUCK_GEN_OUT} are set): scans transformed jars
 * for still-unmapped {@code net/minecraftforge/} owners, keeps those with a same-named class at the conventional
 * NeoForge package, and writes the members that exist on the target with the same name and owner-mapped descriptor to
 * the file consumed by {@link GeneratedOwnerTable}. Existing hand-written entries are never overridden.
 */
class OwnerTableGenerator {
    private static final String[][] PREFIXES = {
        {"net/minecraftforge/event/", "net/neoforged/neoforge/event/"},
        {"net/minecraftforge/client/event/", "net/neoforged/neoforge/client/event/"},
        {"net/minecraftforge/fml/event/", "net/neoforged/fml/event/"},
        {"net/minecraftforge/forgespi/language/", "net/neoforged/neoforgespi/language/"},
        {"net/minecraftforge/fml/InterModComms", "net/neoforged/fml/InterModComms"},
        {"net/minecraftforge/common/util/FakePlayer", "net/neoforged/neoforge/common/util/FakePlayer"},
    };

    /** Same-named classes whose NeoForge counterpart is posted differently or is a different concept. */
    private static final Set<String> EXCLUDED_PREFIXES = Set.of(
            "net/minecraftforge/event/entity/living/LivingDamageEvent", "net/minecraftforge/event/TickEvent");

    static String newOwnerFor(String old) {
        if ("net/minecraftforge/eventbus/api/Event".equals(old)) return "net/neoforged/bus/api/Event";
        for (String ex : EXCLUDED_PREFIXES) if (old.startsWith(ex)) return null;
        for (String[] p : PREFIXES) if (old.startsWith(p[0])) return p[1] + old.substring(p[0].length());
        return null;
    }

    @Test
    void generate() throws Exception {
        String dir = System.getenv("FORGESTUCK_SCAN_DIR");
        String out = System.getenv("FORGESTUCK_GEN_OUT");
        assumeTrue(dir != null && out != null, "generator not requested");

        Set<String> owners = new TreeSet<>();
        Map<String, Set<String>> uses = new TreeMap<>();
        try (var jars = Files.list(Path.of(dir))) {
            for (Path jar : jars.filter(p -> p.toString().endsWith(".jar")).toList()) scan(jar, owners, uses);
        }

        ForgeOwnerMappings existing = ForgeOwnerMappings.defaults();
        Map<String, String> candidates = new TreeMap<>();
        for (String old : owners) {
            if (existing.get(old) != null) continue;
            String neo = newOwnerFor(old);
            if (neo != null && classExists(neo)) candidates.put(old, neo);
        }

        StringBuilder sb = new StringBuilder("# Generated by OwnerTableGenerator; verified by reflection against NeoForge.\n");
        for (Map.Entry<String, String> c : candidates.entrySet()) {
            Class<?> target = Class.forName(c.getValue().replace('/', '.'), false, loader());
            Set<String> ok = new TreeSet<>();
            boolean eventBase = c.getKey().equals("net/minecraftforge/eventbus/api/Event");
            for (String use : uses.getOrDefault(c.getKey(), Set.of())) {
                int sep = use.indexOf('\0');
                String name = use.substring(0, sep);
                String desc = use.substring(sep + 1);
                if (eventBase && !"<init>()V".equals(name + desc)) continue;
                if (exists(target, name, mapDescriptor(desc, candidates))) ok.add(name + desc);
            }
            sb.append(c.getKey()).append(" -> ").append(c.getValue()).append('\n');
            for (String m : ok) sb.append("  ").append(m).append('\n');
        }
        Files.writeString(Path.of(out), sb.toString(), StandardCharsets.UTF_8);
        System.out.println("GENERATED " + candidates.size() + " owners");
    }

    static ClassLoader loader() {
        return OwnerTableGenerator.class.getClassLoader();
    }

    static boolean classExists(String internal) {
        try {
            Class.forName(internal.replace('/', '.'), false, loader());
            return true;
        } catch (ClassNotFoundException | LinkageError e) {
            return false;
        }
    }

    /** Maps legacy descriptor owner tokens through the default table plus the candidates being generated. */
    static String mapDescriptor(String desc, Map<String, String> extra) {
        ForgeOwnerMappings defaults = ForgeOwnerMappings.defaults();
        java.util.regex.Matcher m = java.util.regex.Pattern.compile("L([^;()\\[]+);").matcher(desc);
        StringBuilder sb = new StringBuilder();
        while (m.find()) {
            String o = m.group(1);
            var e = defaults.get(o);
            String mapped = e != null ? e.newOwner() : extra.getOrDefault(o, o);
            m.appendReplacement(sb, java.util.regex.Matcher.quoteReplacement("L" + mapped + ";"));
        }
        m.appendTail(sb);
        return sb.toString();
    }

    /** True when {@code target} has a public constructor/method/field with the given name and descriptor. */
    static boolean exists(Class<?> target, String name, String desc) {
        try {
            if ("<init>".equals(name)) {
                for (Constructor<?> c : target.getConstructors()) {
                    if (Type.getConstructorDescriptor(c).equals(desc)) return true;
                }
                return false;
            }
            int paren = desc.indexOf('(');
            if (paren == 0) {
                for (Method m : target.getMethods()) {
                    if (m.getName().equals(name) && Type.getMethodDescriptor(m).equals(desc)) return true;
                }
                return false;
            }
            for (Field f : target.getFields()) {
                if (f.getName().equals(name) && Type.getDescriptor(f.getType()).equals(desc)) return true;
            }
            return false;
        } catch (LinkageError e) {
            return false;
        }
    }

    private static void scan(Path jar, Set<String> owners, Map<String, Set<String>> uses) throws IOException {
        try (JarFile jf = new JarFile(jar.toFile())) {
            for (JarEntry e : java.util.Collections.list(jf.entries())) {
                if (!e.getName().endsWith(".class") || e.getName().startsWith("META-INF/")) continue;
                byte[] bytes;
                try (InputStream in = jf.getInputStream(e)) {
                    bytes = in.readAllBytes();
                }
                if (!new String(bytes, StandardCharsets.ISO_8859_1).contains("net/minecraftforge/")) continue;
                new ClassReader(bytes).accept(new ClassRemapper(new ClassVisitor(Opcodes.ASM9) {}, new Remapper() {
                    @Override
                    public String map(String n) {
                        if (n.startsWith("net/minecraftforge/")) owners.add(n);
                        return n;
                    }
                }), 0);
                ClassNode node = new ClassNode();
                new ClassReader(bytes).accept(node, 0);
                for (MethodNode m : node.methods) {
                    for (AbstractInsnNode insn : m.instructions.toArray()) {
                        if (insn instanceof MethodInsnNode c) record(uses, c.owner, c.name, c.desc);
                        else if (insn instanceof FieldInsnNode f) record(uses, f.owner, f.name, f.desc);
                        else if (insn instanceof InvokeDynamicInsnNode d) {
                            for (Object a : d.bsmArgs) if (a instanceof Handle h) record(uses, h.getOwner(), h.getName(), h.getDesc());
                        }
                    }
                }
                if (node.superName != null && node.superName.startsWith("net/minecraftforge/")) {
                    record(uses, node.superName, "<init>", "()V");
                }
            }
        }
    }

    private static void record(Map<String, Set<String>> uses, String owner, String name, String desc) {
        if (owner.startsWith("net/minecraftforge/")) {
            uses.computeIfAbsent(owner, k -> new TreeSet<>()).add(name + '\0' + desc);
        }
    }
}
